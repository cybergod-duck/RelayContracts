const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('wallet', {
    exists: () => ipcRenderer.invoke('wallet:exists'),
    devUnlock: () => ipcRenderer.invoke('wallet:devUnlock'),
    create: (pw) => ipcRenderer.invoke('wallet:create', pw),
    unlock: (pw) => ipcRenderer.invoke('wallet:unlock', pw),
    setPin: (pin) => ipcRenderer.invoke('wallet:setPin', pin),
    unlockWithPin: (pin) => ipcRenderer.invoke('wallet:unlockWithPin', pin),
    lock: () => ipcRenderer.invoke('wallet:lock'),
    balance: () => ipcRenderer.invoke('wallet:balance'),
    address: () => ipcRenderer.invoke('wallet:address'),
    send: (to, amount, networkKey, token) => ipcRenderer.invoke('wallet:send', to, amount, networkKey, token),
    txHistory: () => ipcRenderer.invoke('wallet:txHistory'),
    generateQR: (text) => ipcRenderer.invoke('wallet:generateQR', text),
    relayWrap: (amountEth, networkKey) => ipcRenderer.invoke('relay:wrap', amountEth, networkKey),
    relayBoostV3: (amountEth, networkKey) => ipcRenderer.invoke('relay:boostV3', amountEth, networkKey),
    sweepToUsdc: (networkKey) => ipcRenderer.invoke('relay:sweepToUsdc', networkKey),
    customBridge: (fromKey, toKey, token, amount) => ipcRenderer.invoke('relay:customBridge', fromKey, toKey, token, amount),
    relayWethBalance: () => ipcRenderer.invoke('relay:wethBalance'),
    usdcBalance: () => ipcRenderer.invoke('wallet:usdcBalance'),
    estimateGas: (to, amountEth, networkKey) => ipcRenderer.invoke('wallet:estimateGas', to, amountEth, networkKey),
    exportKey: () => ipcRenderer.invoke('wallet:exportKey'),
    exportKeyWithPassword: (pw) => ipcRenderer.invoke('wallet:exportKeyWithPassword', pw),
    exportDevKey: () => ipcRenderer.invoke('wallet:exportDevKey'),
    exportKeyWithPin: (pin) => ipcRenderer.invoke('wallet:exportKeyWithPin', pin),
    exportAll: () => ipcRenderer.invoke('wallet:exportAll'),
    deployPolygon: () => ipcRenderer.invoke('wallet:deployPolygon'),
    deployNetwork: (networkKey) => ipcRenderer.invoke('wallet:deployNetwork', networkKey),
    getContractState: (networkKey, contractAddress) => ipcRenderer.invoke('wallet:getContractState', networkKey, contractAddress),
    updateTreasury: (networkKey, contractAddress, newTreasury) => ipcRenderer.invoke('wallet:updateTreasury', networkKey, contractAddress, newTreasury),
    transferOwnership: (networkKey, contractAddress, newOwner) => ipcRenderer.invoke('wallet:transferOwnership', networkKey, contractAddress, newOwner),
    withdrawETH: (networkKey, contractAddress) => ipcRenderer.invoke('wallet:withdrawETH', networkKey, contractAddress),
    withdrawToken: (networkKey, contractAddress, tokenAddress) => ipcRenderer.invoke('wallet:withdrawToken', networkKey, contractAddress, tokenAddress),
    getContractsList: () => ipcRenderer.invoke('wallet:getContractsList'),
    bridgePolygonToBase:  () => ipcRenderer.invoke('relay:sweepToUsdc', 'polygon'),
    bridgeArbitrumToBase: () => ipcRenderer.invoke('relay:sweepToUsdc', 'arbitrum'),
    bridgeOptimismToBase: () => ipcRenderer.invoke('relay:sweepToUsdc', 'optimism'),
    bridgeBscToBase:      () => ipcRenderer.invoke('relay:sweepToUsdc', 'bsc'),
    bridgeLineaToBase:    () => ipcRenderer.invoke('relay:sweepToUsdc', 'linea'),
    polygonAddresses: () => ipcRenderer.invoke('wallet:polygonAddresses'),
    baseAddresses: () => ipcRenderer.invoke('wallet:baseAddresses'),
    arbitrumAddresses: () => ipcRenderer.invoke('wallet:arbitrumAddresses'),
    optimismAddresses: () => ipcRenderer.invoke('wallet:optimismAddresses'),
    bscAddresses: () => ipcRenderer.invoke('wallet:bscAddresses'),
    lineaAddresses: () => ipcRenderer.invoke('wallet:lineaAddresses'),
    getAddressBook: () => ipcRenderer.invoke('wallet:getAddressBook'),
    saveAddress: (label, address, network) => ipcRenderer.invoke('wallet:saveAddress', label, address, network),
    deleteAddress: (address) => ipcRenderer.invoke('wallet:deleteAddress', address),
    deleteAddressLabel: (label) => ipcRenderer.invoke('wallet:deleteAddressLabel', label),
    getAccounts: () => ipcRenderer.invoke('wallet:getAccounts'),
    addAccount: (label, privateKey) => ipcRenderer.invoke('wallet:addAccount', label, privateKey),
    switchAccount: (address) => ipcRenderer.invoke('wallet:switchAccount', address),
    deleteAccount: (address) => ipcRenderer.invoke('wallet:deleteAccount', address),
    resizeWindow: (w, h) => ipcRenderer.invoke('window:resize', w, h),
    closeApp: () => ipcRenderer.invoke('window:close')
});
